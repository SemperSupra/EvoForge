 const during=await page.locator('.grid').evaluate(e=>e.getBoundingClientRect().top+scrollY);
 assert.ok(Math.abs(baseline-during)<=1,JSON.stringify({baseline,during,initialGeometry,playingGeometry:await geometry()}));
 await page.getByRole('button',{name:'Hold',exact:true}).click();
 const after=await page.locator('.grid').evaluate(e=>e.getBoundingClientRect().top+scrollY);
 assert.ok(Math.abs(baseline-after)<=1,JSON.stringify({baseline,after}));
 await page.getByText('Reality Rings · live selection',{exact:true}).click();
 const rings=page.locator('.evolution-lenses details').first();
 await rings.locator('.ring-compact').waitFor({state:'visible'});
 assert.equal(await rings.locator('.ring-visual').isVisible(),false);
 assert.equal(await rings.locator('.ring-compact [data-lens-candidate]').count(),16);
 await page.screenshot({path:out+'/04a-phone-stage-browser.png'});
 await page.setViewportSize({width:820,height:1180});
 await rings.locator('.ring-lanes').waitFor({state:'visible'});
 assert.equal(await rings.locator('.ring-lanes [data-lens-candidate]').count(),16);
 await page.screenshot({path:out+'/04b-tablet-lanes.png'});
 await page.setViewportSize({width:1440,height:900});
