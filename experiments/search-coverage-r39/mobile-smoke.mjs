 await page.getByLabel('Reality Rings layout').selectOption('rings');
 await rings.locator('svg [data-candidate-id]').first().waitFor();
 assert.equal(await page.locator('.evolution-lenses details').first().locator('svg [data-candidate-id]').count(),16);
